test('capture, explicit confirmation, completion, persistence and offline editing', async ({ page, context }) => {
  await page.getByLabel("What's on your mind?", { exact: true }).fill('I need groceries tomorrow and have to clean my apartment');
  await page.getByRole('button', { name: 'Organize my thoughts' }).click();
  await expect(page.getByRole('heading', { name: 'A few possible next steps' })).toBeVisible();
  const unsaved = await page.evaluate(async () => { const request = indexedDB.open('mindpilot-local-v1'); const db = await new Promise<IDBDatabase>(resolve => { request.onsuccess = () => resolve(request.result); }); const get = db.transaction('app').objectStore('app').get('data'); return await new Promise<number>(resolve => { get.onsuccess = () => { resolve(get.result?.tasks?.length ?? 0); db.close(); }; }); });
  expect(unsaved).toBe(0);
  await page.getByRole('button', { name: 'Confirm 2 activities' }).click();
  await expect(page.getByRole('heading', { name: 'A little less on your mind.' })).toBeVisible();
  await page.getByRole('button', { name: 'Open planner', exact: true }).click();
  await page.getByRole('button', { name: 'Thursday, November 26' }).click();
  await expect(page.getByText('Groceries', { exact: true })).toBeVisible();
  await page.getByRole('checkbox', { name: 'Complete Groceries' }).click();
  await expect(page.getByRole('checkbox', { name: 'Complete Groceries' })).toBeChecked();
  await page.evaluate(() => navigator.serviceWorker.ready.then(() => true));
  await page.reload();
  await context.setOffline(true);
  await page.reload();
  await expect(page.getByText('You’re offline.', { exact: false })).toBeVisible();
  await page.getByRole('button', { name: 'Thursday, November 26' }).click();
  await expect(page.getByRole('checkbox', { name: 'Complete Groceries' })).toBeChecked();
  await page.getByRole('button', { name: 'Edit Groceries', exact: true }).click();
  await page.getByLabel('Activity name', { exact: true }).fill('Groceries and coffee');
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByText('Groceries and coffee', { exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: 'Thursday, November 26' }).click();
  await expect(page.getByText('Groceries and coffee', { exact: true })).toBeVisible();
  await nav(page, 'Progress');
  await expect(page.getByText('1 of 2 activities due this week')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});

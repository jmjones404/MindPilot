test('failed writes do not show success or discard suggestions', async ({ page }) => {
  await page.getByLabel("What's on your mind?", { exact: true }).fill('Buy apples tomorrow');
  await page.getByRole('button', { name: 'Organize my thoughts' }).click();
  await expect(page.getByRole('button', { name: 'Confirm 1 activity' })).toBeEnabled();
  await page.evaluate(() => { IDBDatabase.prototype.transaction = () => { throw new DOMException('Disk full', 'QuotaExceededError'); }; });
  await page.getByRole('button', { name: 'Confirm 1 activity' }).click();
  await expect(page.getByRole('alert')).toContainText('Not saved');
  await expect(page.getByRole('button', { name: 'Confirm 1 activity' })).toBeEnabled();
  await expect(page.getByRole('heading', { name: 'A little less on your mind.' })).toHaveCount(0);
});
test('manifest, home-screen assets, navigation, dark mode and mobile overflow', async ({ page, request }) => {
  const manifest = await (await request.get('/manifest.webmanifest')).json();
  expect(manifest.display).toBe('standalone'); expect(manifest.start_url).toBe('/'); expect(manifest.icons.some((i: { purpose: string }) => i.purpose === 'maskable')).toBe(true);
  for (const icon of manifest.icons) expect((await request.get(icon.src)).ok()).toBe(true);
  await page.getByRole('button', { name: 'Open settings', exact: true }).click();
  await page.getByRole('button', { name: 'Dark', exact: true }).click();
  await expect(page.locator('html')).toHaveClass('dark');
  await page.getByRole('button', { name: 'Close dialog' }).click();
  for (const name of ['Home', 'MindDump', 'Planner', 'My Rhythm', 'Progress']) { await nav(page, name); expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), name).toBe(true); }
  await page.reload(); await expect(page.locator('html')).toHaveClass('dark');
  await page.screenshot({ path: 'test-results/progress-mobile-dark.png', fullPage: true });
});
